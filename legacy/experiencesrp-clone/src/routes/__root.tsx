function RootShell({ children }: { children: ReactNode }) {
  // The one site-wide robots rule. Rendered outside HeadContent so a deeper
  // route's own robots meta cannot replace it; while indexing is OFF crawlers
  // apply the most restrictive of the two (noindex,nofollow). ON -> no tag here,
  // and per-page rules (profile completeness floor, marketing pages) decide.
  const enabled = useRouterState({
    select: (s) =>
      (s.matches.find((m) => m.routeId === "__root__")?.loaderData as
        | { siteIndexingEnabled?: boolean }
        | undefined)?.siteIndexingEnabled === true,
  });
  const robots = siteRobotsMeta(enabled);
  return (
    <html lang="en">
      <head>
        {robots ? <meta name={robots.name} content={robots.content} /> : null}
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  useEffect(() => {
    const { data } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
    });
    return () => data.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <Toaster />
    </QueryClientProvider>
  );
}

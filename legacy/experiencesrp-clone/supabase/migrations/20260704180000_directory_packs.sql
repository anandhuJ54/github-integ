-- Directory / citation network model for Ring 2 (profiles_presence).
--
-- Two tables, "cable-channel" model:
--   exp_directory_packs        — the canonical catalog of every citation site,
--                                deduped and reused across categories. tier +
--                                pack_family enable product packaging later.
--   exp_category_directory_map — which directories a given gcid gets, via the
--                                universal network (all categories) or a
--                                vertical-authority family pack.
--
-- Principle: SELECT from this verified catalog, never invent per category. A
-- category's Ring 2 nodes are generated by joining the map, not by free
-- generation. verification_status marks what we can stand behind as a real site
-- today (verified) vs surfaced-but-unconfirmed (unverified) — unverified rows
-- are captured for completeness but should not earn score points until confirmed.

CREATE TABLE IF NOT EXISTS exp_directory_packs (
  directory_key       text PRIMARY KEY,                  -- stable slug, e.g. 'healthgrades'
  directory_name      text NOT NULL,                     -- display, e.g. 'Healthgrades'
  canonical_domain    text,                              -- e.g. 'healthgrades.com'
  url_pattern         text,                              -- e.g. 'healthgrades.com/physician/{id}'
  schema_type         text NOT NULL DEFAULT 'WebSite',   -- schema.org type for the presence node
  schema_property     text NOT NULL DEFAULT 'sameAs',    -- graph property the node connects via
  tier                smallint NOT NULL DEFAULT 3        -- 1 majors, 2 aggregators/generalists, 3 long-tail / niche
                        CHECK (tier BETWEEN 1 AND 4),
  pack_family         text NOT NULL DEFAULT 'universal', -- 'universal' or a vertical family key
  connection_method   text NOT NULL DEFAULT 'manual'
                        CHECK (connection_method IN ('oauth','etl','crm_sync','api','manual','rss','platform')),
  verification_status text NOT NULL DEFAULT 'verified'
                        CHECK (verification_status IN ('verified','unverified')),
  is_active           boolean NOT NULL DEFAULT true,
  notes               text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_dirpacks_family ON exp_directory_packs(pack_family);
CREATE INDEX IF NOT EXISTS idx_dirpacks_tier   ON exp_directory_packs(tier);
CREATE INDEX IF NOT EXISTS idx_dirpacks_active ON exp_directory_packs(is_active);

CREATE TABLE IF NOT EXISTS exp_category_directory_map (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  gcid          text NOT NULL REFERENCES gbp_categories(gcid),
  directory_key text NOT NULL REFERENCES exp_directory_packs(directory_key),
  source        text NOT NULL DEFAULT 'family'          -- how it was assigned
                  CHECK (source IN ('universal','family','manual')),
  is_active     boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT unique_gcid_directory UNIQUE (gcid, directory_key)
);

CREATE INDEX IF NOT EXISTS idx_catdir_gcid ON exp_category_directory_map(gcid);
CREATE INDEX IF NOT EXISTS idx_catdir_dir  ON exp_category_directory_map(directory_key);

ALTER TABLE exp_directory_packs        ENABLE ROW LEVEL SECURITY;
ALTER TABLE exp_category_directory_map ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public read exp_directory_packs" ON public.exp_directory_packs;
CREATE POLICY "Public read exp_directory_packs"
  ON public.exp_directory_packs FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Auth write exp_directory_packs" ON public.exp_directory_packs;
CREATE POLICY "Auth write exp_directory_packs"
  ON public.exp_directory_packs FOR ALL TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public read exp_category_directory_map" ON public.exp_category_directory_map;
CREATE POLICY "Public read exp_category_directory_map"
  ON public.exp_category_directory_map FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Auth write exp_category_directory_map" ON public.exp_category_directory_map;
CREATE POLICY "Auth write exp_category_directory_map"
  ON public.exp_category_directory_map FOR ALL TO authenticated USING (true) WITH CHECK (true);

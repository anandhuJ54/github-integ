"""One declarative Base / MetaData for every Surface's ORM classes (`<surface>/src/models/`).

Every Surface puts its tables in its own Postgres schema (`__table_args__ = {"schema": "<surface>"}`,
AGENTS.md §4), but they all share this MetaData so a foreign key into another Surface's table
resolves by name (`ForeignKey("xmp.accounts.id")`) without importing that Surface's model.

The tables still in `public` stay in the generated Core catalog `_base/db/tables.py` (its own
MetaData). Migrations stay hand-written SQL; the classes must match them (the naming convention
gives the constraint names the migrations use). Queries built from the classes run on the psycopg
connections through `_base.db.sql` (rows come back as dicts; there is no ORM Session).
"""
from __future__ import annotations

from datetime import datetime

from sqlalchemy import BigInteger, DateTime, Identity, MetaData, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class IdMixin:
    # GENERATED BY DEFAULT (not ALWAYS) so a data load can insert existing ids; the load resets
    # the sequence afterwards.
    id: Mapped[int] = mapped_column(BigInteger, Identity(always=False), primary_key=True)


class TimestampMixin:
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )

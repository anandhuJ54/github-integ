-- Connections page table for the local database (srp/connections-page-schema, task 1).
--
-- LOCAL ONLY: adds ONE table to the `srp_cleanup` schema of the local `v3_local` database. It is not an Alembic revision and not part of the closed SQL stream
-- (`surface-api/migrations/`). It alters no existing table and touches no other schema; no legacy table (`social_media_connections` included) is read or changed.
--
-- Run it only as the owner role, only on v3_local, after home_schema.sql, home_schema_hardening.sql, srs_schema.sql, profile_schema.sql, insights_schema.sql and
-- web_analytics_schema.sql, and after a schema-only backup:
--     pg_dump --schema-only --schema=srp_cleanup v3_local > <private file outside the repo>
--     psql v3_local -v ON_ERROR_STOP=1 -f surface-api/srp/db/local/connections_schema.sql
-- It is re-runnable (if not exists) and runs in one transaction. It writes no rows: the seed (`surfaces.srp.seat.seed_home`) fills the table.
--
-- What it adds:
--   * connected_accounts: one row per seat and account of the page (eleven providers: google_business, search_console, youtube, facebook, instagram, linkedin, x, zillow,
--     yelp, website_cms, loan_system). Each row has its STATE (connected, available, matched or partial), the time of the last sync, a SOURCE label and a TRUST TIER
--     (self_declared < imported < platform_observed < authority_verified < owner_verified, AGENTS.md section 3). "matched" and "partial" exist only for zillow and yelp
--     (found by NORA, no sign-in needed); the last sync is null exactly when the state is "available". The table holds no token, secret, sign-in or account identifier:
--     the page only shows what is connected.
-- Conventions as in home_schema.sql: bigint identity id, no row-level security, no trigger and no function; access is by grant only: nothing for anon, authenticated or
-- PUBLIC, and select/insert/update/delete for v3_app. All rows are mock data (is_mock defaults to true).
--
-- Rollback: the commented block at the end (nothing depends on the table).

begin;

create table if not exists srp_cleanup.connected_accounts (
    id bigint generated by default as identity not null,
    tier_agent_id bigint not null,
    provider varchar(20) not null,
    state varchar(9) not null,
    synced_at timestamp,
    source varchar(60) not null,
    trust_tier varchar(20) not null,
    is_mock boolean not null default true,
    constraint pk_connected_accounts primary key (id),
    constraint fk_connected_accounts_tier_agent_id foreign key (tier_agent_id) references srp_cleanup.tier_agents (id),
    constraint uq_connected_accounts_seat_provider unique (tier_agent_id, provider),
    constraint ck_connected_accounts_provider check (provider in (
        'google_business', 'search_console', 'youtube', 'facebook', 'instagram', 'linkedin', 'x', 'zillow', 'yelp', 'website_cms', 'loan_system')),
    constraint ck_connected_accounts_state check (state in ('connected', 'available', 'matched', 'partial')),
    constraint ck_connected_accounts_trust_tier check (trust_tier in ('self_declared', 'imported', 'platform_observed', 'authority_verified', 'owner_verified')),
    constraint ck_connected_accounts_source check (btrim(source) <> ''),
    -- matched and partial (found by NORA, no sign-in) exist only for the two directories
    constraint ck_connected_accounts_matchable check (state in ('connected', 'available') or provider in ('zillow', 'yelp')),
    -- an account has been synced exactly when it is not merely available
    constraint ck_connected_accounts_synced check ((synced_at is null) = (state = 'available'))
);

-- no separate seat index: the unique (tier_agent_id, provider) index already leads with the seat

comment on table srp_cleanup.connected_accounts is 'Connections page, one row per seat and account: its state, last sync, source and trust tier. Holds no token, secret or account identifier. Mock rows written by the seed.';
comment on column srp_cleanup.connected_accounts.id is 'Row id.';
comment on column srp_cleanup.connected_accounts.tier_agent_id is 'The seat this row belongs to (tier_agents.id).';
comment on column srp_cleanup.connected_accounts.provider is 'Which account: google_business, search_console, youtube, facebook, instagram, linkedin, x, zillow, yelp, website_cms or loan_system.';
comment on column srp_cleanup.connected_accounts.state is 'connected, available (not connected yet), matched or partial (zillow and yelp only: found by NORA, no sign-in).';
comment on column srp_cleanup.connected_accounts.synced_at is 'When the account last synced; null exactly when the state is available.';
comment on column srp_cleanup.connected_accounts.source is 'Where the state came from, as a label, for example From your sign-in.';
comment on column srp_cleanup.connected_accounts.trust_tier is 'How far the state is trusted: self_declared, imported, platform_observed, authority_verified or owner_verified.';
comment on column srp_cleanup.connected_accounts.is_mock is 'True for mock data written by the seed.';

revoke all on srp_cleanup.connected_accounts from anon, authenticated, public;
grant select, insert, update, delete on srp_cleanup.connected_accounts to v3_app;

commit;


-- Insights page tables for the local database (srp/insights-page-schema, task 1).
--
-- LOCAL ONLY: adds FOUR tables to the `srp_cleanup` schema of the local `v3_local` database and ONE unique constraint, (id, tier_agent_id), to Home's
-- `home_competitors` (so a competitor position cannot name another seat's rival; the same pattern as uq_home_snapshots_id_seat). It is not an Alembic
-- revision and not part of the closed SQL stream (`surface-api/migrations/`). It touches no other table and no other schema; no legacy table is read or changed.
--
-- Run it only as the owner role, only on v3_local, after home_schema.sql, home_schema_hardening.sql, srs_schema.sql and profile_schema.sql, and after a
-- schema-only backup:
--     pg_dump --schema-only --schema=srp_cleanup v3_local > <private file outside the repo>
--     psql v3_local -v ON_ERROR_STOP=1 -f surface-api/srp/db/local/insights_schema.sql
-- It is re-runnable (if not exists, and a catalog check for the constraint) and runs in one transaction. It writes no rows: the seed
-- (`surfaces.srp.seat.seed_home`) fills the tables.
--
-- What it adds:
--   * insights_visibility: one row per seat and metric (search_views, maps_views, calls, directions, website_clicks, profile_views): the figure for the last
--     period_days days, its SOURCE label and its TRUST TIER (self_declared < imported < platform_observed < authority_verified < owner_verified, AGENTS.md
--     section 3).
--   * insights_ai_engines: one row per seat and AI engine (chatgpt, gemini, perplexity): answers checked, answers that name the seat, and a short note.
--     It splits home_snapshots.ai_cited / ai_checked per engine; the seed makes the rows add up to those two figures (not a trigger).
--   * insights_competitor_positions: a rival's average map position, one row per rival (home_competitors). The seat's own average is computed from its
--     49 map ranks, not stored.
--   * insights_spot_leaders: the top 3 businesses of one map spot (home_map_cells): position 1 to 3, either "You" (is_you, no name) or a rival's name.
-- Conventions as in home_schema.sql: bigint identity id, `timestamp` columns hold UTC, no row-level security, no trigger and no function; access is by grant
-- only: nothing for anon, authenticated or PUBLIC, and select/insert/update/delete for v3_app. All rows are mock data (is_mock defaults to true).
--
-- Rollback: the commented block at the end (nothing depends on the tables or the constraint).

begin;

-- a competitor position needs (competitor, seat) to be a key of home_competitors
do $$
begin
    if not exists (
        select 1 from pg_constraint
        where conrelid = 'srp_cleanup.home_competitors'::regclass and conname = 'uq_home_competitors_id_seat'
    ) then
        alter table srp_cleanup.home_competitors add constraint uq_home_competitors_id_seat unique (id, tier_agent_id);
    end if;
end $$;

create table if not exists srp_cleanup.insights_visibility (
    id bigint generated by default as identity not null,
    tier_agent_id bigint not null,
    metric varchar(20) not null,
    value integer not null,
    period_days integer not null default 30,
    source varchar(60) not null,
    trust_tier varchar(20) not null,
    is_mock boolean not null default true,
    constraint pk_insights_visibility primary key (id),
    constraint fk_insights_visibility_tier_agent_id foreign key (tier_agent_id) references srp_cleanup.tier_agents (id),
    constraint uq_insights_visibility_seat_metric unique (tier_agent_id, metric),
    constraint ck_insights_visibility_metric check (metric in ('search_views', 'maps_views', 'calls', 'directions', 'website_clicks', 'profile_views')),
    constraint ck_insights_visibility_value check (value >= 0),
    constraint ck_insights_visibility_period_days check (period_days > 0),
    constraint ck_insights_visibility_trust_tier check (trust_tier in ('self_declared', 'imported', 'platform_observed', 'authority_verified', 'owner_verified'))
);

create table if not exists srp_cleanup.insights_ai_engines (
    id bigint generated by default as identity not null,
    tier_agent_id bigint not null,
    engine varchar(12) not null,
    cited integer not null,
    checked integer not null,
    note varchar(120),
    is_mock boolean not null default true,
    constraint pk_insights_ai_engines primary key (id),
    constraint fk_insights_ai_engines_tier_agent_id foreign key (tier_agent_id) references srp_cleanup.tier_agents (id),
    constraint uq_insights_ai_engines_seat_engine unique (tier_agent_id, engine),
    constraint ck_insights_ai_engines_engine check (engine in ('chatgpt', 'gemini', 'perplexity')),
    constraint ck_insights_ai_engines_cited check (cited >= 0),
    constraint ck_insights_ai_engines_cited_le_checked check (cited <= checked)
);

create table if not exists srp_cleanup.insights_competitor_positions (
    id bigint generated by default as identity not null,
    tier_agent_id bigint not null,
    competitor_id bigint not null,
    avg_position numeric(3, 1) not null,
    is_mock boolean not null default true,
    constraint pk_insights_competitor_positions primary key (id),
    constraint fk_insights_competitor_positions_tier_agent_id foreign key (tier_agent_id) references srp_cleanup.tier_agents (id),
    -- the rival must belong to the same seat
    constraint fk_insights_competitor_positions_competitor foreign key (competitor_id, tier_agent_id) references srp_cleanup.home_competitors (id, tier_agent_id),
    constraint uq_insights_competitor_positions_competitor unique (competitor_id),
    constraint ck_insights_competitor_positions_avg_position check (avg_position >= 1)
);

create table if not exists srp_cleanup.insights_spot_leaders (
    id bigint generated by default as identity not null,
    cell_id bigint not null,
    position smallint not null,
    name varchar(160),
    is_you boolean not null,
    is_mock boolean not null default true,
    constraint pk_insights_spot_leaders primary key (id),
    constraint fk_insights_spot_leaders_cell_id foreign key (cell_id) references srp_cleanup.home_map_cells (id) on delete cascade,
    constraint uq_insights_spot_leaders_cell_position unique (cell_id, position),
    constraint ck_insights_spot_leaders_position check (position between 1 and 3),
    -- "You" has no name; a rival has one
    constraint ck_insights_spot_leaders_you_or_name check (is_you = (name is null))
);

create index if not exists idx_insights_visibility_tier_agent_id on srp_cleanup.insights_visibility (tier_agent_id);
create index if not exists idx_insights_ai_engines_tier_agent_id on srp_cleanup.insights_ai_engines (tier_agent_id);
create index if not exists idx_insights_competitor_positions_tier_agent_id on srp_cleanup.insights_competitor_positions (tier_agent_id);
create index if not exists idx_insights_spot_leaders_cell_id on srp_cleanup.insights_spot_leaders (cell_id);

comment on table srp_cleanup.insights_visibility is 'Insights page, one row per seat and visibility metric: the figure for the last period_days days with its source and trust tier. Mock rows written by the seed.';

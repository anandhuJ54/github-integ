comment on column srp_cleanup.insights_visibility.tier_agent_id is 'The seat this row belongs to (tier_agents.id).';
comment on column srp_cleanup.insights_visibility.metric is 'Which figure: search_views, maps_views, calls, directions, website_clicks or profile_views.';
comment on column srp_cleanup.insights_visibility.value is 'The count for the period (zero or more).';
comment on column srp_cleanup.insights_visibility.period_days is 'How many days the count covers (default 30).';
comment on column srp_cleanup.insights_visibility.source is 'Where the figure came from, as the page shows it, for example From Google.';
comment on column srp_cleanup.insights_visibility.trust_tier is 'How far the figure is trusted: self_declared, imported, platform_observed, authority_verified or owner_verified.';
comment on column srp_cleanup.insights_visibility.is_mock is 'True for mock data written by the seed.';

comment on table srp_cleanup.insights_ai_engines is 'Insights page, one row per seat and AI engine: answers checked and answers that name the seat. Splits home_snapshots.ai_cited and ai_checked per engine. Mock rows written by the seed.';
comment on column srp_cleanup.insights_ai_engines.id is 'Row id.';
comment on column srp_cleanup.insights_ai_engines.tier_agent_id is 'The seat this row belongs to (tier_agents.id).';
comment on column srp_cleanup.insights_ai_engines.engine is 'The AI engine: chatgpt, gemini or perplexity.';
comment on column srp_cleanup.insights_ai_engines.cited is 'Answers that name the seat (zero up to checked).';
comment on column srp_cleanup.insights_ai_engines.checked is 'Answers checked on this engine.';
comment on column srp_cleanup.insights_ai_engines.note is 'A short note about what the engine says; null when there is none.';
comment on column srp_cleanup.insights_ai_engines.is_mock is 'True for mock data written by the seed.';

comment on table srp_cleanup.insights_competitor_positions is 'Insights page, one row per rival (home_competitors): its average map position. The seat''s own average is computed from its map ranks. Mock rows written by the seed.';
comment on column srp_cleanup.insights_competitor_positions.id is 'Row id.';
comment on column srp_cleanup.insights_competitor_positions.tier_agent_id is 'The seat this row belongs to; the rival must belong to the same seat.';
comment on column srp_cleanup.insights_competitor_positions.competitor_id is 'The rival (home_competitors.id).';
comment on column srp_cleanup.insights_competitor_positions.avg_position is 'The rival''s average position on the seat''s map, one decimal, 1.0 or more.';
comment on column srp_cleanup.insights_competitor_positions.is_mock is 'True for mock data written by the seed.';

comment on table srp_cleanup.insights_spot_leaders is 'Insights page, the top 3 businesses of one map spot (home_map_cells): the seat itself or a rival. Mock rows written by the seed.';
comment on column srp_cleanup.insights_spot_leaders.id is 'Row id.';
comment on column srp_cleanup.insights_spot_leaders.cell_id is 'The map spot (home_map_cells.id); the rows go with the cell.';
comment on column srp_cleanup.insights_spot_leaders.position is 'Place in the spot''s top 3: 1, 2 or 3.';
comment on column srp_cleanup.insights_spot_leaders.name is 'The rival''s name; null exactly when the row is the seat itself.';
comment on column srp_cleanup.insights_spot_leaders.is_you is 'True when the row is the seat itself (shown as You).';
comment on column srp_cleanup.insights_spot_leaders.is_mock is 'True for mock data written by the seed.';

revoke all on srp_cleanup.insights_visibility from anon, authenticated, public;
grant select, insert, update, delete on srp_cleanup.insights_visibility to v3_app;
revoke all on srp_cleanup.insights_ai_engines from anon, authenticated, public;
grant select, insert, update, delete on srp_cleanup.insights_ai_engines to v3_app;
revoke all on srp_cleanup.insights_competitor_positions from anon, authenticated, public;
grant select, insert, update, delete on srp_cleanup.insights_competitor_positions to v3_app;
revoke all on srp_cleanup.insights_spot_leaders from anon, authenticated, public;
grant select, insert, update, delete on srp_cleanup.insights_spot_leaders to v3_app;


-- Network page tables for the local database (srp/network-page-schema, task 1).
--
-- LOCAL ONLY: adds TWO tables to the `srp_cleanup` schema of the local `v3_local` database. It is not an Alembic revision and not part of the closed SQL stream
-- (`surface-api/migrations/`). It alters no existing table and touches no other schema; no legacy table (`partners`, `pin_partner_profiles`, `referral_sents`,
-- `referral_requests`, `referral_histories`, `referral_emails`, `invite_partners`, `invite_signups`) is read or changed.
--
-- Run it only as the owner role, only on v3_local, after home_schema.sql, home_schema_hardening.sql, srs_schema.sql, profile_schema.sql, insights_schema.sql,
-- web_analytics_schema.sql and connections_schema.sql, and after a schema-only backup:
--     pg_dump --schema-only --schema=srp_cleanup v3_local > <private file outside the repo>
--     psql v3_local -v ON_ERROR_STOP=1 -f surface-api/srp/db/local/network_schema.sql
-- It is re-runnable (if not exists) and runs in one transaction. It writes no rows: the seed (`surfaces.srp.seat.seed_home`) fills the tables.
--
-- What it adds:
--   * network_partners: the people on a seat's Partners tab, one row per seat and partner, in display order (position). Each has a display name, a company, a ROLE (Agent,
--     Title or Inspector), a STATE (promoted, request, suggested or saved), the REASON the page shows beside it (a kind, and for the kinds that need them a count or a date,
--     so the text is computed, never stored), a SOURCE label and a TRUST TIER (self_declared < imported < platform_observed < authority_verified < owner_verified,
--     AGENTS.md section 3). The database enforces which reason a state allows: promoted none, request "asked", suggested "zillow" or "closings" (with a count of at least 1),
--     saved "saved" (with a date).
--   * network_referrals: the three lists on the Referrals tab (received, requested, given), one row per seat, list and position: a display name, a short detail, the date,
--     a STATUS (new, followed, closed for received; waiting, replied for requested; thanked, done for given), an optional PARTNER (a given referral always has one, a requested
--     one never; it can only be a partner of the same seat), a source label and a trust tier.
--   No table holds an email address, a phone number, a message or any other contact detail of a person.
-- Conventions as in home_schema.sql: bigint identity id, no row-level security, no trigger and no function; access is by grant only: nothing for anon, authenticated or
-- PUBLIC, and select/insert/update/delete for v3_app. All rows are mock data (is_mock defaults to true).
--
-- Rollback: the commented block at the end (the referrals first: they reference the partners).

begin;

create table if not exists srp_cleanup.network_partners (
    id bigint generated by default as identity not null,
    tier_agent_id bigint not null,
    position integer not null,
    name varchar(80) not null,
    company varchar(80) not null,
    role varchar(10) not null,
    state varchar(9) not null,
    reason_kind varchar(8),
    reason_count integer,
    reason_on date,
    source varchar(60) not null,
    trust_tier varchar(20) not null,
    is_mock boolean not null default true,
    constraint pk_network_partners primary key (id),
    constraint fk_network_partners_tier_agent_id foreign key (tier_agent_id) references srp_cleanup.tier_agents (id),
    constraint uq_network_partners_seat_position unique (tier_agent_id, position),
    constraint uq_network_partners_seat_name unique (tier_agent_id, name),
    -- lets a referral point to a partner of its own seat only
    constraint uq_network_partners_id_seat unique (id, tier_agent_id),
    constraint ck_network_partners_position check (position >= 1),
    constraint ck_network_partners_name check (btrim(name) <> ''),
    constraint ck_network_partners_company check (btrim(company) <> ''),
    constraint ck_network_partners_role check (role in ('Agent', 'Title', 'Inspector')),
    constraint ck_network_partners_state check (state in ('promoted', 'request', 'suggested', 'saved')),
    constraint ck_network_partners_trust_tier check (trust_tier in ('self_declared', 'imported', 'platform_observed', 'authority_verified', 'owner_verified')),
    constraint ck_network_partners_source check (btrim(source) <> ''),
    constraint ck_network_partners_reason_kind check (reason_kind is null or reason_kind in ('asked', 'zillow', 'closings', 'saved')),
    -- the reason a state allows
    -- (coalesce: a null reason kind makes the comparisons null, which a CHECK would accept)
    constraint ck_network_partners_reason_by_state check (coalesce(case state
        when 'promoted' then reason_kind is null
        when 'request' then reason_kind = 'asked'
        when 'suggested' then reason_kind in ('zillow', 'closings')
        else reason_kind = 'saved' end, false)),
    -- a count (at least 1) exactly for the kinds that cite one; a date exactly for "saved"
    constraint ck_network_partners_reason_count check ((reason_count is not null) = coalesce(reason_kind in ('zillow', 'closings'), false) and (reason_count is null or reason_count >= 1)),
    constraint ck_network_partners_reason_on check ((reason_on is not null) = coalesce(reason_kind = 'saved', false))
);

create table if not exists srp_cleanup.network_referrals (
    id bigint generated by default as identity not null,
    tier_agent_id bigint not null,
    list_key varchar(9) not null,
    position integer not null,
    name varchar(80) not null,
    detail varchar(80) not null,
    partner_id bigint,
    status varchar(8) not null,
    occurred_on date not null,
    source varchar(60) not null,
    trust_tier varchar(20) not null,
    is_mock boolean not null default true,
    constraint pk_network_referrals primary key (id),
    constraint fk_network_referrals_tier_agent_id foreign key (tier_agent_id) references srp_cleanup.tier_agents (id),
    -- a partner of the same seat (not enforced while partner_id is null)
    constraint fk_network_referrals_partner foreign key (partner_id, tier_agent_id) references srp_cleanup.network_partners (id, tier_agent_id),
    constraint uq_network_referrals_seat_list_position unique (tier_agent_id, list_key, position),
    constraint ck_network_referrals_position check (position >= 1),
    constraint ck_network_referrals_list_key check (list_key in ('received', 'requested', 'given')),
    constraint ck_network_referrals_name check (btrim(name) <> ''),
    constraint ck_network_referrals_detail check (btrim(detail) <> ''),
    constraint ck_network_referrals_trust_tier check (trust_tier in ('self_declared', 'imported', 'platform_observed', 'authority_verified', 'owner_verified')),
    constraint ck_network_referrals_source check (btrim(source) <> ''),
    -- a list allows only its own statuses; a given referral has a partner and a requested one has none
    constraint ck_network_referrals_status_by_list check (
        (list_key = 'received' and status in ('new', 'followed', 'closed'))
        or (list_key = 'requested' and status in ('waiting', 'replied') and partner_id is null)
        or (list_key = 'given' and status in ('thanked', 'done') and partner_id is not null))
);

-- no separate seat indexes: each table's unique key already leads with the seat


-- Profile page tables for the local database (srp/profile-page-schema, task 1).
--
-- LOCAL ONLY: adds TWO tables to the `srp_cleanup` schema of the local `v3_local` database. It is not an Alembic revision and not part of the closed
-- SQL stream (`surface-api/migrations/`). It alters no existing table and touches no other schema; no legacy table is read or changed.
--
-- Run it only as the owner role, only on v3_local, after home_schema.sql, home_schema_hardening.sql and srs_schema.sql, and after a schema-only backup:
--     pg_dump --schema-only --schema=srp_cleanup v3_local > <private file outside the repo>
--     psql v3_local -v ON_ERROR_STOP=1 -f surface-api/srp/db/local/profile_schema.sql
-- It is re-runnable (if not exists) and runs in one transaction. It writes no rows: the seed (`surfaces.srp.seat.seed_home`) fills the tables.
--
-- What it adds:
--   * profile_facts: one row per seat and fact (18 facts): the SOURCE label, the TRUST TIER (self_declared < imported < platform_observed < authority_verified
--     < owner_verified, AGENTS.md section 3) and the date of the fact, and the VALUE only for the ten facts that have no coherent home in the existing tables
--     (address, hours, nmls, licensed_in, products, service_areas, designations, awards, education, company). The other eight facts (name, title, photo, bio,
--     year_started, office_phone, mobile_phone, email) are read from tier_agents and users as they are, so their value here MUST be null: a check makes a
--     second copy of an existing value impossible. A value is a non-blank string, or (products) a non-empty list of strings; a blank fact is a missing one: no row.
--   * profile_graph_groups: one row per seat and source group of the page's "Expertise graph" card (identity, contact, licence, products, reviews, presence)
--     with its fact count. The page adds the counts up; the real graph is written only through the governed path and is not touched.
-- Conventions as in home_schema.sql: bigint identity id, `timestamp` columns hold UTC, no row-level security, no trigger and no function; access is by grant
-- only: nothing for anon, authenticated or PUBLIC, and select/insert/update/delete for v3_app. All rows are mock data (is_mock defaults to true).
--
-- Rollback: the commented block at the end (nothing depends on the tables).

begin;

create table if not exists srp_cleanup.profile_facts (
    id bigint generated by default as identity not null,
    tier_agent_id bigint not null,
    field varchar(20) not null,
    value jsonb,
    source varchar(60) not null,
    trust_tier varchar(20) not null,
    confirmed_at timestamp,
    is_mock boolean not null default true,
    constraint pk_profile_facts primary key (id),
    constraint fk_profile_facts_tier_agent_id foreign key (tier_agent_id) references srp_cleanup.tier_agents (id),
    constraint uq_profile_facts_seat_field unique (tier_agent_id, field),
    constraint ck_profile_facts_field check (field in (
        'name', 'title', 'photo', 'bio', 'year_started', 'office_phone', 'mobile_phone', 'email',
        'address', 'hours', 'nmls', 'licensed_in', 'products', 'service_areas', 'designations', 'awards', 'education', 'company')),
    constraint ck_profile_facts_trust_tier check (trust_tier in ('self_declared', 'imported', 'platform_observed', 'authority_verified', 'owner_verified')),
    -- no second copy: a value exists exactly for the ten facts that live here
    constraint ck_profile_facts_value_only_for_own_fields check (
        (value is null) = (field in ('name', 'title', 'photo', 'bio', 'year_started', 'office_phone', 'mobile_phone', 'email'))),
    -- a non-blank string, or a non-empty list of strings
    constraint ck_profile_facts_value_shape check (
        value is null
        or (jsonb_typeof(value) = 'string' and btrim(value #>> '{}') <> '')
        or (jsonb_typeof(value) = 'array' and jsonb_array_length(value) > 0 and not jsonb_path_exists(value, 'strict $[*] ? (@.type() != "string")')))
);

create table if not exists srp_cleanup.profile_graph_groups (
    id bigint generated by default as identity not null,
    tier_agent_id bigint not null,
    group_key varchar(12) not null,
    facts integer not null,
    is_mock boolean not null default true,
    constraint pk_profile_graph_groups primary key (id),
    constraint fk_profile_graph_groups_tier_agent_id foreign key (tier_agent_id) references srp_cleanup.tier_agents (id),
    constraint uq_profile_graph_groups_seat_group unique (tier_agent_id, group_key),
    constraint ck_profile_graph_groups_group_key check (group_key in ('identity', 'contact', 'licence', 'products', 'reviews', 'presence')),
    constraint ck_profile_graph_groups_facts check (facts >= 0)
);

create index if not exists idx_profile_facts_tier_agent_id on srp_cleanup.profile_facts (tier_agent_id);
create index if not exists idx_profile_graph_groups_tier_agent_id on srp_cleanup.profile_graph_groups (tier_agent_id);

comment on table srp_cleanup.profile_facts is 'Profile page, one row per seat and fact: its source, trust tier and date, and the value only for facts with no home in the existing tables. Mock rows written by the seed.';
comment on column srp_cleanup.profile_facts.id is 'Row id.';
comment on column srp_cleanup.profile_facts.tier_agent_id is 'The seat this row belongs to (tier_agents.id).';
comment on column srp_cleanup.profile_facts.field is 'Which fact: name, title, photo, bio, year_started, office_phone, mobile_phone, email (value read from tier_agents and users), or address, hours, nmls, licensed_in, products, service_areas, designations, awards, education, company (value stored here).';
comment on column srp_cleanup.profile_facts.value is 'The fact''s value as JSON: a string, or a list of strings for products. Null exactly for the eight facts whose value lives in tier_agents and users.';
comment on column srp_cleanup.profile_facts.source is 'Where the fact came from, as the page shows it, for example From LinkedIn or Confirmed by you.';
comment on column srp_cleanup.profile_facts.trust_tier is 'How far the fact is trusted: self_declared, imported, platform_observed, authority_verified or owner_verified.';
comment on column srp_cleanup.profile_facts.confirmed_at is 'When the fact was confirmed (UTC); null when the source has no date.';
comment on column srp_cleanup.profile_facts.is_mock is 'True for mock data written by the seed.';

comment on table srp_cleanup.profile_graph_groups is 'Profile page Expertise graph, one row per seat and source group: how many facts the group holds. Mock counts written by the seed; the page adds them up.';
comment on column srp_cleanup.profile_graph_groups.id is 'Row id.';
comment on column srp_cleanup.profile_graph_groups.tier_agent_id is 'The seat this row belongs to (tier_agents.id).';
comment on column srp_cleanup.profile_graph_groups.group_key is 'The source group: identity, contact, licence, products, reviews or presence.';
comment on column srp_cleanup.profile_graph_groups.facts is 'Number of facts in the group (zero or more).';
comment on column srp_cleanup.profile_graph_groups.is_mock is 'True for mock data written by the seed.';

revoke all on srp_cleanup.profile_facts from anon, authenticated, public;
grant select, insert, update, delete on srp_cleanup.profile_facts to v3_app;
revoke all on srp_cleanup.profile_graph_groups from anon, authenticated, public;
grant select, insert, update, delete on srp_cleanup.profile_graph_groups to v3_app;

commit;


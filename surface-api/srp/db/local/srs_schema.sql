-- SRS page table for the local database (srp/srs-page-schema, task 1).
--
-- LOCAL ONLY: adds ONE table and ONE column to the `srp_cleanup` schema of the local `v3_local` database. It is not an Alembic revision and not
-- part of the closed SQL stream (`surface-api/migrations/`). It touches no other schema and no legacy table: `srs_config_*`,
-- `user_search_rank_scores` and `ai_authority_stats` are neither read nor changed (the SRS page keeps the SRS v5 lanes in `home_score_lanes`).
--
-- Run it only as the owner role, only on v3_local, after home_schema.sql and home_schema_hardening.sql, and after a schema-only backup:
--     pg_dump --schema-only --schema=srp_cleanup v3_local > <private file outside the repo>
--     psql v3_local -v ON_ERROR_STOP=1 -f surface-api/srp/db/local/srs_schema.sql
-- It is re-runnable (if not exists) and runs in one transaction. It writes no rows: the seed (`surfaces.srp.seat.seed_home`) fills the table.
--
-- What it adds:
--   * srs_lane_gaps: one row per seat and lane (10 per seat): the "you vs rival" texts, whether the seat has none of what the lane measures,
--     and the lane's action on the SRS page. The lane must be one of the 10 SRS v5 lanes (foreign key), a seat has one row per lane (unique),
--     and the action target is one of the screens the page can open (check). Earned and open points are NOT stored: they come from
--     home_snapshot_lanes, whose triggers already keep a snapshot at 10 lanes within their budgets and summing to the total.
--   * home_score_lanes.short_name: the short label ("GBP", "Q&A"); the page falls back to `name` when it is null.
-- Conventions as in home_schema.sql: bigint identity id, `timestamp` columns hold UTC, no row-level security, no trigger and no function;
-- access is by grant only: nothing for anon, authenticated or PUBLIC, and select/insert/update/delete for v3_app.
-- All rows are mock data (is_mock defaults to true).
--
-- Rollback: the commented block at the end (nothing depends on the table or the column).

begin;

alter table srp_cleanup.home_score_lanes add column if not exists short_name varchar(24);

create table if not exists srp_cleanup.srs_lane_gaps (
    id bigint generated by default as identity not null,
    tier_agent_id bigint not null,
    lane_id bigint not null,
    you_text varchar(200) not null,
    rival_text varchar(200) not null,
    note varchar(200),
    is_missing boolean not null default false,
    action_label varchar(60) not null,
    action_target varchar(16) not null,
    is_mock boolean not null default true,
    constraint pk_srs_lane_gaps primary key (id),
    constraint fk_srs_lane_gaps_tier_agent_id foreign key (tier_agent_id) references srp_cleanup.tier_agents (id),
    constraint fk_srs_lane_gaps_lane_id foreign key (lane_id) references srp_cleanup.home_score_lanes (id),
    constraint uq_srs_lane_gaps_seat_lane unique (tier_agent_id, lane_id),
    constraint ck_srs_lane_gaps_action_target check (action_target in ('profile', 'voce', 'website', 'connections', 'reviews', 'chat', 'billing'))
);

create index if not exists idx_srs_lane_gaps_tier_agent_id on srp_cleanup.srs_lane_gaps (tier_agent_id);
create index if not exists idx_srs_lane_gaps_lane_id on srp_cleanup.srs_lane_gaps (lane_id);

comment on column srp_cleanup.home_score_lanes.short_name is 'Short label for the SRS page (GBP, Q&A); null means the page uses name.';

comment on table srp_cleanup.srs_lane_gaps is 'SRS page, one row per seat and SRS v5 lane: the you-vs-rival texts and the lane action. Mock text written by the seed; earned and open points come from home_snapshot_lanes.';
comment on column srp_cleanup.srs_lane_gaps.id is 'Row id.';
comment on column srp_cleanup.srs_lane_gaps.tier_agent_id is 'The seat this row belongs to (tier_agents.id).';
comment on column srp_cleanup.srs_lane_gaps.lane_id is 'The SRS v5 lane (home_score_lanes.id).';
comment on column srp_cleanup.srs_lane_gaps.you_text is 'What the seat has, for example ''0 articles''.';
comment on column srp_cleanup.srs_lane_gaps.rival_text is 'What the market leader has, for example ''14 articles''.';
comment on column srp_cleanup.srs_lane_gaps.note is 'An extra line shown on the lane, for example ''31 in the last 12 months''; null when there is none.';
comment on column srp_cleanup.srs_lane_gaps.is_missing is 'True when the seat has none of what the lane measures (the page shows Missing).';
comment on column srp_cleanup.srs_lane_gaps.action_label is 'Button text on the lane.';
comment on column srp_cleanup.srs_lane_gaps.action_target is 'Where the button leads: profile, voce, website, connections, reviews, chat or billing.';
comment on column srp_cleanup.srs_lane_gaps.is_mock is 'True for mock data written by the seed.';

revoke all on srp_cleanup.srs_lane_gaps from anon, authenticated, public;
grant select, insert, update, delete on srp_cleanup.srs_lane_gaps to v3_app;

commit;


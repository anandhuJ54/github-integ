-- Web analytics page table for the local database (srp/web-analytics-page-schema, task 1).
--
-- LOCAL ONLY: adds ONE table to the `srp_cleanup` schema of the local `v3_local` database. It is not an Alembic revision and not part of the closed SQL stream
-- (`surface-api/migrations/`). It alters no existing table and touches no other schema; no legacy table is read or changed.
--
-- Run it only as the owner role, only on v3_local, after home_schema.sql, home_schema_hardening.sql, srs_schema.sql, profile_schema.sql and insights_schema.sql, and
-- after a schema-only backup:
--     pg_dump --schema-only --schema=srp_cleanup v3_local > <private file outside the repo>
--     psql v3_local -v ON_ERROR_STOP=1 -f surface-api/srp/db/local/web_analytics_schema.sql
-- It is re-runnable (if not exists) and runs in one transaction. It writes no rows: the seed (`surfaces.srp.seat.seed_home`) fills the table.
--
-- What it adds:
--   * web_checks: one row per seat and check of the page's audit (ten checks: entity_markup, nap, indexing, service_pages, speed, ai_readiness, content, conversion,
--     reviews_on_site, security). Each row has its STATE (fail, warn or pass), the RESULT line the page shows, a SOURCE label and a TRUST TIER (self_declared <
--     imported < platform_observed < authority_verified < owner_verified, AGENTS.md section 3). Four checks are SCORED (entity_markup, nap, indexing, service_pages):
--     they carry the points earned and the points available, which the seed makes add up to the seat's SRS v5 website lane; the state of a scored check is derived from
--     its points (full points pass, none fail, in between warn) and the database enforces it. Two checks carry a HEADLINE for the tile ("LCP 3.1 s", "2 of 5").
-- Conventions as in home_schema.sql: bigint identity id, no row-level security, no trigger and no function; access is by grant only: nothing for anon, authenticated or
-- PUBLIC, and select/insert/update/delete for v3_app. All rows are mock data (is_mock defaults to true).
--
-- Rollback: the commented block at the end (nothing depends on the table).

begin;

create table if not exists srp_cleanup.web_checks (
    id bigint generated by default as identity not null,
    tier_agent_id bigint not null,
    check_key varchar(20) not null,
    state varchar(4) not null,
    result varchar(240) not null,
    headline varchar(40),
    points integer,
    points_max integer,
    source varchar(60) not null,
    trust_tier varchar(20) not null,
    is_mock boolean not null default true,
    constraint pk_web_checks primary key (id),
    constraint fk_web_checks_tier_agent_id foreign key (tier_agent_id) references srp_cleanup.tier_agents (id),
    constraint uq_web_checks_seat_key unique (tier_agent_id, check_key),
    constraint ck_web_checks_check_key check (check_key in (
        'entity_markup', 'nap', 'indexing', 'service_pages', 'speed', 'ai_readiness', 'content', 'conversion', 'reviews_on_site', 'security')),
    constraint ck_web_checks_state check (state in ('fail', 'warn', 'pass')),
    constraint ck_web_checks_trust_tier check (trust_tier in ('self_declared', 'imported', 'platform_observed', 'authority_verified', 'owner_verified')),
    constraint ck_web_checks_result check (btrim(result) <> ''),
    constraint ck_web_checks_headline_text check (headline is null or btrim(headline) <> ''),
    -- a headline exactly for the two checks whose tile shows one
    constraint ck_web_checks_headline_keys check ((headline is not null) = (check_key in ('speed', 'ai_readiness'))),
    -- points and their maximum go together, and only the four scored checks have them
    constraint ck_web_checks_points_pair check ((points is null) = (points_max is null)),
    constraint ck_web_checks_scored_keys check ((points_max is not null) = (check_key in ('entity_markup', 'nap', 'indexing', 'service_pages'))),
    constraint ck_web_checks_points_max check (points_max is null or points_max > 0),
    constraint ck_web_checks_points_range check (points is null or (points >= 0 and points <= points_max)),
    -- the state of a scored check follows its points
    constraint ck_web_checks_state_follows_points check (
        points is null or state = case when points = points_max then 'pass' when points = 0 then 'fail' else 'warn' end)
);

create index if not exists idx_web_checks_tier_agent_id on srp_cleanup.web_checks (tier_agent_id);

comment on table srp_cleanup.web_checks is 'Web analytics page, one row per seat and audit check: its state, result line, optional points, source and trust tier. The four scored checks add up to the seat''s website lane. Mock rows written by the seed.';
comment on column srp_cleanup.web_checks.id is 'Row id.';
comment on column srp_cleanup.web_checks.tier_agent_id is 'The seat this row belongs to (tier_agents.id).';
comment on column srp_cleanup.web_checks.check_key is 'Which check: entity_markup, nap, indexing, service_pages, speed, ai_readiness, content, conversion, reviews_on_site or security.';
comment on column srp_cleanup.web_checks.state is 'fail, warn or pass. For a scored check it follows the points (full pass, none fail, in between warn).';
comment on column srp_cleanup.web_checks.result is 'The result line the page shows for the check, for example Indexed; no sitemap.';
comment on column srp_cleanup.web_checks.headline is 'The short value of the check''s tile: LCP 3.1 s for speed, 2 of 5 for ai_readiness; null for every other check.';
comment on column srp_cleanup.web_checks.points is 'Points earned (zero up to points_max); null for the six unscored checks.';
comment on column srp_cleanup.web_checks.points_max is 'Points available (more than zero); null for the six unscored checks.';
comment on column srp_cleanup.web_checks.source is 'Where the result came from, as a label, for example From your site scan.';
comment on column srp_cleanup.web_checks.trust_tier is 'How far the result is trusted: self_declared, imported, platform_observed, authority_verified or owner_verified.';
comment on column srp_cleanup.web_checks.is_mock is 'True for mock data written by the seed.';

revoke all on srp_cleanup.web_checks from anon, authenticated, public;
grant select, insert, update, delete on srp_cleanup.web_checks to v3_app;

commit;


"""Real-Postgres checks for the sign-in lock logic (srp/local-login-srp-home, second-model review finding 3).

The fakes cannot show that the count-and-lock statement is atomic or that no connection is held during
bcrypt. These run against a real database in a scratch schema that is created and dropped here, and are
skipped unless SRP_TEST_DATABASE_URL points at a database you are happy to create a temporary schema in
(for example the local one):

    SRP_TEST_DATABASE_URL=postgresql://localhost:5432/v3_local uv run pytest srp/tests/test_auth_integration.py
"""
from __future__ import annotations

import os
import threading
import time
import uuid

import bcrypt
import psycopg
import pytest

from _base.config import get_settings
from _base.db import session as db_session
from surfaces.srp.auth import services

URL = os.environ.get("SRP_TEST_DATABASE_URL")
pytestmark = pytest.mark.skipif(not URL, reason="SRP_TEST_DATABASE_URL is not set")

PASSWORD = "correct horse battery"
EMAIL = "it.user@example.test"


@pytest.fixture
def schema(monkeypatch):
    name = "srp_it_" + uuid.uuid4().hex[:8]
    with psycopg.connect(URL, autocommit=True) as c:
        c.execute(f"create schema {name}")
        c.execute(
            f"""create table {name}.users (id bigint generated by default as identity primary key,
                email varchar(255), first_name varchar(255), last_name varchar(255),
                password_digest varchar(255), failed_attempts int default 0, locked_at timestamp,
                deleted_at timestamp, deactivated_at timestamp, is_manual_deactivated boolean default false,
                last_login_at timestamp, num_logins int default 0)"""
        )
        c.execute(f"create table {name}.tier_agents (id bigint generated by default as identity primary key, user_id bigint, deleted_at timestamp)")
        c.execute(f"create table {name}.agent_mappings (id bigint generated by default as identity primary key, tier_agent_id bigint, is_primary boolean)")
        digest = bcrypt.hashpw(PASSWORD.encode(), bcrypt.gensalt(rounds=4)).decode()
        c.execute(f"insert into {name}.users (email, first_name, password_digest) values (%s, 'It', %s)", (EMAIL, digest))
        c.execute(f"insert into {name}.tier_agents (user_id) values (1)")
    monkeypatch.setenv("DATABASE_URL", URL)
    monkeypatch.setenv("SRP_LOCAL_SCHEMA", name)
    monkeypatch.setenv("DB_POOL_MAX", "1")  # one connection: anything that holds it during bcrypt shows up as waiting
    get_settings.cache_clear()
    db_session.close_pools()
    yield name
    db_session.close_pools()
    get_settings.cache_clear()
    with psycopg.connect(URL, autocommit=True) as c:
        c.execute(f"drop schema {name} cascade")


def _row(schema: str) -> dict:
    with psycopg.connect(URL, autocommit=True, row_factory=psycopg.rows.dict_row) as c:
        return c.execute(f"select failed_attempts, locked_at, num_logins from {schema}.users where id = 1").fetchone()


def test_five_misses_lock_in_the_database_and_a_correct_password_is_then_refused(schema):
    for _ in range(5):
        assert services.authenticate(EMAIL, "wrong-password-1").ok is False
    row = _row(schema)
    assert row["failed_attempts"] == 5 and row["locked_at"] is not None
    assert services.authenticate(EMAIL, PASSWORD).ok is False  # locked
    assert _row(schema)["failed_attempts"] == 5  # a locked user is not counted again


def test_a_lapsed_lock_lets_the_correct_password_in_and_resets_the_count(schema):
    with psycopg.connect(URL, autocommit=True) as c:
        c.execute(f"update {schema}.users set failed_attempts = 5, locked_at = localtimestamp - interval '16 minutes'")
    assert services.authenticate(EMAIL, PASSWORD).ok is True
    row = _row(schema)
    assert row["failed_attempts"] == 0 and row["locked_at"] is None and row["num_logins"] == 1


def test_a_miss_after_a_lapsed_lock_restarts_the_count_at_one(schema):
    with psycopg.connect(URL, autocommit=True) as c:
        c.execute(f"update {schema}.users set failed_attempts = 5, locked_at = localtimestamp - interval '16 minutes'")
    services.authenticate(EMAIL, "wrong-password-1")
    row = _row(schema)
    assert row["failed_attempts"] == 1 and row["locked_at"] is None


def test_many_simultaneous_misses_count_exactly_five_and_lock_once(schema, monkeypatch):
    monkeypatch.setenv("DB_POOL_MAX", "8")
    db_session.close_pools()
    get_settings.cache_clear()
    results: list[bool] = []

    def attempt():
        results.append(services.authenticate(EMAIL, "wrong-password-1").ok)

    threads = [threading.Thread(target=attempt) for _ in range(24)]
    [t.start() for t in threads]
    [t.join() for t in threads]
    row = _row(schema)
    assert results == [False] * 24
    assert row["failed_attempts"] == 5, "lost or extra updates"  # the statement excludes a user who is already locked
    assert row["locked_at"] is not None


def test_no_connection_is_held_while_bcrypt_runs(schema, monkeypatch):
    """With a pool of ONE connection, six sign-ins that each take 0.3 s to hash must overlap. If the
    connection were held during the hash they would queue: 6 x 0.3 s."""
    real = services._check_password

    def slow(password, digest):
        time.sleep(0.3)
        return real(password, digest)

    monkeypatch.setattr(services, "_check_password", slow)
    started = time.perf_counter()
    threads = [threading.Thread(target=services.authenticate, args=(EMAIL, PASSWORD)) for _ in range(6)]
    [t.start() for t in threads]
    [t.join() for t in threads]
    elapsed = time.perf_counter() - started
    assert elapsed < 1.2, f"sign-ins queued behind a held connection ({elapsed:.2f}s)"

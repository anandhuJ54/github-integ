def test_a_second_run_changes_nothing(conn, schema):
    before = conn.execute(
        "select (select count(*) from pg_constraint c join pg_namespace n on n.oid = c.connamespace where n.nspname = %s) as cons, "
        "(select count(*) from pg_indexes where schemaname = %s) as idx, "
        "(select count(*) from information_schema.columns where table_schema = %s) as cols", (schema, schema, schema)).fetchone()
    apply(conn, schema)
    after = conn.execute(
        "select (select count(*) from pg_constraint c join pg_namespace n on n.oid = c.connamespace where n.nspname = %s) as cons, "
        "(select count(*) from pg_indexes where schemaname = %s) as idx, "
        "(select count(*) from information_schema.columns where table_schema = %s) as cols", (schema, schema, schema)).fetchone()
    assert before == after and tables(conn, schema) == sorted(["tier_agents", *TABLES])



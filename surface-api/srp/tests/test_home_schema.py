def _role(conn, name: str) -> bool:
    return bool(conn.execute("select 1 from pg_roles where rolname = %s", (name,)).fetchone())


def test_grants_are_closed_to_anon_authenticated_and_public_and_open_to_the_app_role(conn, schema):
    for t in TABLES:
        acl = conn.execute(
            "select coalesce(r.rolname, 'PUBLIC') as grantee, array_agg(a.privilege_type order by a.privilege_type) as privs "
            "from pg_class c join pg_namespace n on n.oid = c.relnamespace, aclexplode(c.relacl) a "
            "left join pg_roles r on r.oid = a.grantee where n.nspname = %s and c.relname = %s and a.grantee <> c.relowner group by 1",
            (schema, t)).fetchall()
        grants = {r["grantee"]: r["privs"] for r in acl}
        assert "PUBLIC" not in grants and "anon" not in grants and "authenticated" not in grants, (t, grants)
        if _role(conn, "v3_app"):
            assert grants.get("v3_app") == ["DELETE", "INSERT", "SELECT", "UPDATE"], (t, grants)



def test_every_table_has_a_bigint_identity_primary_key_and_plain_timestamps(conn, schema):
    for t in TABLES:
        idcol = conn.execute(
            "select data_type, is_identity, identity_generation from information_schema.columns where table_schema = %s and table_name = %s and column_name = 'id'",
            (schema, t)).fetchone()
        assert idcol == {"data_type": "bigint", "is_identity": "YES", "identity_generation": "BY DEFAULT"}, t
        pk = conn.execute(
            "select a.attname from pg_index i join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any(i.indkey) "
            "where i.indrelid = %s::regclass and i.indisprimary", (f"{schema}.{t}",)).fetchall()
        assert [r["attname"] for r in pk] == ["id"], t
    stamps = conn.execute(
        "select table_name, column_name, data_type from information_schema.columns where table_schema = %s "
        "and table_name like 'home\\_%%' and data_type like 'timestamp%%'", (schema,)).fetchall()
    assert stamps and all(r["data_type"] == "timestamp without time zone" for r in stamps)



def apply(conn, name: str) -> None:
    conn.execute(re.sub(r"\bsrp_cleanup\b", name, script_text()))


def tables(conn, schema: str) -> list[str]:
    return sorted(r["table_name"] for r in conn.execute(
        "select table_name from information_schema.tables where table_schema = %s and table_type = 'BASE TABLE'", (schema,)))


def refused(conn, error, sql: str, params=()) -> None:
    with pytest.raises(error):
        conn.execute(sql, params)



"""The Home tables' DDL script (srp/home-page-schema, task 1): `srp/db/local/home_schema.sql`.

The static tests read the script text and always run. The rest apply the script to a scratch schema, so they need a
database (any database: the scratch schema stands in for `srp_cleanup`, with its own stand-in `tier_agents`) and are skipped unless

    SRP_TEST_DATABASE_URL=postgresql://localhost:5432/<a scratch database> uv run pytest srp/tests/test_home_schema.py

The script names `srp_cleanup`; the fixture swaps in the scratch schema's name. Nothing here touches another schema.
"""
from __future__ import annotations

import os
import re
import uuid
from pathlib import Path

import psycopg
import pytest
from psycopg import errors
from psycopg.rows import dict_row

SCRIPT = Path(__file__).resolve().parents[1] / "db" / "local" / "home_schema.sql"
URL = os.environ.get("SRP_TEST_DATABASE_URL")

TABLES = [
    "home_score_lanes", "home_score_bands", "home_plans", "home_peer_benchmarks", "home_snapshots", "home_snapshot_lanes",
    "home_map_cells", "home_seat_state", "home_competitors", "home_activity", "home_next_moves", "home_locked_features",
    "home_weekly_briefs", "home_weekly_brief_items", "home_review_drafts", "home_events", "home_nora_insights",
]
SEAT_COLUMNS = ["tier_agent_id", "snapshot_id", "brief_id", "lane_id", "plan_id", "band_id"]


def script_text() -> str:
    return SCRIPT.read_text()


def live_sql() -> str:
    """The script without comments (the rollback block is commented out)."""
    return "\n".join(re.sub(r"--.*$", "", line) for line in script_text().splitlines())


# --- static: the text of the script ---------------------------------------------------------------

def test_the_script_exists_and_is_one_transaction():
    sql = live_sql().strip().lower()
    assert sql.startswith("begin;") and sql.rstrip().endswith("commit;"), "one begin ... commit"
    assert sql.count("begin;") == 1 and sql.count("commit;") == 1


def test_it_creates_exactly_the_seventeen_home_tables_in_srp_cleanup():
    created = re.findall(r"create table if not exists (\S+)", live_sql(), flags=re.IGNORECASE)
    assert created == [f"srp_cleanup.{t}" for t in TABLES] or sorted(created) == sorted(f"srp_cleanup.{t}" for t in TABLES)
    assert len(created) == 17 == len(set(created))


def test_it_only_names_the_local_schema_and_never_alters_or_drops():
    sql = live_sql().lower()
    assert "public." not in sql
    for kw in ("drop ", "truncate", "delete from", "update srp_cleanup", "insert into"):
        assert kw not in sql, kw
    # the only ALTER-like statements allowed are none: no existing table is changed
    assert "alter table" not in sql
    for ref in re.findall(r"references\s+(\S+?)\s*\(", sql):
        assert ref in {"srp_cleanup.tier_agents"} | {f"srp_cleanup.{t}" for t in TABLES}, ref


def test_it_adds_no_rls_and_grants_only_to_the_app_role():
    sql = live_sql().lower()
    assert "row level security" not in sql and "create policy" not in sql
    for g in re.findall(r"grant\s+(.*?)\s+on\s+(\S+)\s+to\s+(\S+);", sql, flags=re.DOTALL):
        privileges, _table, role = g
        assert role == "v3_app", role
        assert {p.strip() for p in privileges.split(",")} == {"select", "insert", "update", "delete"}
    for role in ("anon", "authenticated", "public"):
        assert f"to {role}" not in sql


def test_it_has_a_commented_rollback_for_every_table():
    text = script_text()
    for t in TABLES:
        assert re.search(rf"^--\s*drop table if exists srp_cleanup\.{t};", text, flags=re.MULTILINE), t



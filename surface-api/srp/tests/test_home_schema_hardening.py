    conn.execute(f"insert into {s}.home_weekly_brief_items (brief_id, position, label, points) values (%s, 2, 'x2', 1)", (first,))
    with pytest.raises(errors.UniqueViolation):
        conn.execute(f"insert into {s}.home_weekly_brief_items (brief_id, position, label, points) values (%s, 1, 'y', 2)", (first,))



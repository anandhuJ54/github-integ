def apply(conn, schema: str, path: Path) -> None:
    conn.execute(re.sub(r"\bsrp_cleanup\b", schema, path.read_text()))


@pytest.fixture
def s(conn):
    name = "srp_it_" + uuid.uuid4().hex[:8]
    conn.execute(f"create schema {name}")
    conn.execute(f"create table {name}.tier_agents (id bigint generated by default as identity primary key, user_id bigint)")
    conn.execute(f"insert into {name}.tier_agents (id, user_id) overriding system value values (1, 1), (2, 2)")
    try:
        apply(conn, name, BASE)
        apply(conn, name, HARD)
        conn.execute(f"insert into {name}.home_score_bands (name, min_points, position) values ('Building', 0, 1)")
        conn.execute(f"insert into {name}.home_score_lanes (key, name, max_points, position) values ('a', 'A', 100, 1), ('b', 'B', 50, 2)")
        conn.execute(f"insert into {name}.home_plans (key, name, position, items) values ('core', 'Core', 1, '[]'::jsonb)")
        yield name
    finally:
        conn.execute(f"drop schema if exists {name} cascade")


def snap(conn, s: str, seat: int, total: int, day: int = 1) -> int:
    return conn.execute(
        f"insert into {s}.home_snapshots (tier_agent_id, as_of, total, band_id) values (%s, '2026-10-0{day} 12:00', %s, (select id from {s}.home_score_bands limit 1)) returning id",
        (seat, total)).fetchone()["id"]


def lane(conn, s: str, snapshot: int, key: str, points: int) -> None:
    conn.execute(f"insert into {s}.home_snapshot_lanes (snapshot_id, lane_id, points) values (%s, (select id from {s}.home_score_lanes where key = %s), %s)", (snapshot, key, points))


def test_a_second_run_changes_nothing(conn, s):
    def counts():
        return conn.execute(
            "select (select count(*) from pg_constraint c join pg_namespace n on n.oid = c.connamespace where n.nspname = %s) as cons, "
            "(select count(*) from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace where n.nspname = %s and not t.tgisinternal) as trg, "
            "(select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = %s) as fns", (s, s, s)).fetchone()
    before = counts()
    apply(conn, s, HARD)
    assert counts() == before and before["trg"] >= 3 and before["fns"] >= 2


@pytest.mark.parametrize("table,cols", [
    ("home_competitors", ("tier_agent_id", "position")),
    ("home_next_moves", ("tier_agent_id", "position")),
    ("home_nora_insights", ("tier_agent_id", "position")),
    ("home_activity", ("tier_agent_id", "label")),
])
def test_one_row_per_seat_and_position_or_label(conn, s, table, cols):
    ins = {
        "home_competitors": f"insert into {s}.home_competitors (tier_agent_id, name, score, position) values (1, 'R', 500, 1)",
        "home_next_moves": f"insert into {s}.home_next_moves (tier_agent_id, icon, title, target, position) values (1, 'pen', 'T', 'voce', 1)",
        "home_nora_insights": f"insert into {s}.home_nora_insights (tier_agent_id, title, body, action, position) values (1, 'T', 'B', 'voce', 1)",
        "home_activity": f"insert into {s}.home_activity (tier_agent_id, label, status) values (1, 'L', 'done')",
    }[table]
    conn.execute(ins)
    with pytest.raises(errors.UniqueViolation):
        conn.execute(ins)
    other = ins.replace("values (1,", "values (2,")
    conn.execute(other)  # another seat may use the same position or label
    again = ins.replace("'L'", "'M'") if table == "home_activity" else ins.replace(", 1)", ", 2)")
    conn.execute(again)  # the same seat may add another position or label


def test_one_brief_per_seat_and_week_and_one_item_per_position(conn, s):
    b = lambda seat, week: conn.execute(f"insert into {s}.home_weekly_briefs (tier_agent_id, week_start, next_move_target) values (%s, %s, 'voce') returning id", (seat, week)).fetchone()["id"]
    first = b(1, "2026-10-19")

def test_the_claim_snapshot_must_belong_to_the_same_seat(conn, s):
    mine, theirs = snap(conn, s, 1, 100), snap(conn, s, 2, 100)
    state = lambda seat, claim: conn.execute(
        f"insert into {s}.home_seat_state (tier_agent_id, plan_id, trial_started_at, trial_days, claim_snapshot_id) values (%s, (select id from {s}.home_plans limit 1), '2026-10-01', 30, %s)", (seat, claim))
    with pytest.raises(errors.ForeignKeyViolation):
        state(1, theirs)
    state(1, mine)
    with pytest.raises(errors.ForeignKeyViolation):
        conn.execute(f"update {s}.home_seat_state set claim_snapshot_id = %s where tier_agent_id = 1", (theirs,))
    state(2, None)  # no claim snapshot is allowed


def test_deleting_the_claim_snapshot_clears_only_the_pointer(conn, s):
    mine = snap(conn, s, 1, 100)
    conn.execute(f"insert into {s}.home_seat_state (tier_agent_id, plan_id, trial_started_at, trial_days, claim_snapshot_id) values (1, (select id from {s}.home_plans limit 1), '2026-10-01', 30, %s)", (mine,))
    conn.execute(f"delete from {s}.home_snapshots where id = %s", (mine,))
    assert conn.execute(f"select tier_agent_id, claim_snapshot_id from {s}.home_seat_state").fetchone() == {"tier_agent_id": 1, "claim_snapshot_id": None}


def test_lane_points_cannot_exceed_the_lanes_maximum(conn, s):
    with pytest.raises(errors.CheckViolation), conn.transaction():
        sid = snap(conn, s, 1, 51)       # the total matches the lane, so only the lane's maximum (50) can refuse it
        lane(conn, s, sid, "b", 51)
    sid = snap(conn, s, 1, 50)
    lane(conn, s, sid, "b", 50)   # exactly the maximum is fine
    with pytest.raises(errors.CheckViolation):
        conn.execute(f"update {s}.home_snapshot_lanes set points = 51")


def test_a_lane_maximum_cannot_be_lowered_below_points_already_scored(conn, s):
    sid = snap(conn, s, 1, 40)
    lane(conn, s, sid, "a", 40)
    with pytest.raises(errors.CheckViolation):
        conn.execute(f"update {s}.home_score_lanes set max_points = 39 where key = 'a'")
    conn.execute(f"update {s}.home_score_lanes set max_points = 40 where key = 'a'")


def test_lane_points_must_add_up_to_the_snapshot_total_at_commit(conn, s):
    with conn.transaction():
        sid = snap(conn, s, 1, 100)
        lane(conn, s, sid, "a", 60); lane(conn, s, sid, "b", 40)      # 100: fine, and order of inserts inside a transaction does not matter
    with pytest.raises(errors.CheckViolation), conn.transaction():
        sid = snap(conn, s, 1, 90, day=2)
        lane(conn, s, sid, "a", 60); lane(conn, s, sid, "b", 40)  # 100 against a total of 90
    with pytest.raises(errors.CheckViolation), conn.transaction():
        conn.execute(f"update {s}.home_snapshots set total = 99 where total = 100")
    with pytest.raises(errors.CheckViolation), conn.transaction():
        conn.execute(f"update {s}.home_snapshot_lanes set points = 39 where points = 40")
    with pytest.raises(errors.CheckViolation), conn.transaction():
        conn.execute(f"delete from {s}.home_snapshot_lanes where points = 40")   # 60 left against 100
    with conn.transaction():   # the total may be changed first and the lanes after, inside one transaction
        conn.execute(f"update {s}.home_snapshots set total = 110 where total = 100")
        conn.execute(f"update {s}.home_snapshot_lanes set points = 60 where points = 60 and lane_id = (select id from {s}.home_score_lanes where key = 'a')")
        conn.execute(f"update {s}.home_snapshot_lanes set points = 50 where lane_id = (select id from {s}.home_score_lanes where key = 'b')")
        conn.execute(f"update {s}.home_snapshots set total = 100 where total = 110")
        conn.execute(f"update {s}.home_snapshot_lanes set points = 40 where lane_id = (select id from {s}.home_score_lanes where key = 'b')")
    with conn.transaction():   # moving points between lanes inside one transaction is fine
        conn.execute(f"update {s}.home_snapshot_lanes set points = 50 where points = 60")
        conn.execute(f"update {s}.home_snapshot_lanes set points = 50 where points = 40")
    assert conn.execute(f"select sum(points) as t from {s}.home_snapshot_lanes").fetchone()["t"] == 100


def test_a_snapshot_with_no_lanes_is_allowed_and_a_cascade_delete_is_fine(conn, s):
    sid = snap(conn, s, 1, 77)   # nothing to add up yet
    with conn.transaction():
        s2 = snap(conn, s, 1, 100, day=2)
        lane(conn, s, s2, "a", 100)
    conn.execute(f"delete from {s}.home_snapshots where id = %s", (s2,))   # lanes go with it, no complaint
    assert sid
